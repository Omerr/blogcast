"""Publish the podcast as a static site (GitHub Pages).

    digest publish presets/blogcast.yaml

The site directory is its own git repo, and its history is squashed to a
single commit on every publish. Audio is regenerable from the ledger, whereas
a linear history of multi-megabyte mp3s would grow without bound — and a
GitHub Pages site is capped at 1 GB.

Layout published to the branch:

    feed.xml        <- what the phone subscribes to
    index.html      <- human-readable episode list
    audio/*.mp3
    .nojekyll       <- serve every file verbatim
"""
from __future__ import annotations

import html
import shutil
import subprocess
from datetime import datetime, timezone
from pathlib import Path

from . import publish as publish_mod
from .config import base_url, load_dotenv, load_spec, resolve
from .models import Episode
from .store import Store

DEFAULT_RETENTION = 80


def _git(site: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(site), *args],
                          check=check, text=True, capture_output=True)


def _publish_cfg(spec: dict) -> dict:
    return spec.get("publish", {}) or {}


def _kept(spec: dict, store: Store) -> list[Episode]:
    """Newest N episodes that still have an audio file on disk."""
    retention = int(_publish_cfg(spec).get("retention", DEFAULT_RETENTION))
    episodes = [ep for ep in store.all_episodes(spec["name"]) if Path(ep.audio_path).exists()]
    episodes.sort(key=lambda e: (publish_mod.aware(e.published), e.number), reverse=True)
    return episodes[:retention]


def _index_html(spec: dict, episodes: list[Episode], base: str) -> str:
    esc = html.escape
    latest = max((f"{publish_mod.aware(e.published):%Y-%m-%d}" for e in episodes), default="—")
    rows = []
    for ep in episodes:
        name = Path(ep.audio_path).name
        when = f"{publish_mod.aware(ep.published):%Y-%m-%d}"
        rows.append(
            f"""    <li>
      <span class="when">{when}</span>
      <a class="title" href="audio/{esc(name)}">{esc(ep.title)}</a>
      <span class="dur">{esc(ep.duration)}</span>
      <audio controls preload="none" src="audio/{esc(name)}"></audio>
    </li>"""
        )
    return f"""<!doctype html>
<html lang="{esc(spec.get('language', 'en-us'))}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(spec.get('title', 'Podcast'))}</title>
<link rel="alternate" type="application/rss+xml" title="{esc(spec.get('title', 'Podcast'))}" href="feed.xml">
<style>
  :root {{ color-scheme: light dark; }}
  body {{ font: 16px/1.5 system-ui, sans-serif; max-width: 46rem; margin: 3rem auto; padding: 0 1rem; }}
  h1 {{ margin-bottom: .25rem; }}
  p.sub {{ color: #6b7280; margin-top: 0; }}
  code {{ background: #8881; padding: .15rem .35rem; border-radius: .25rem; word-break: break-all; }}
  ul {{ list-style: none; padding: 0; }}
  li {{ padding: .9rem 0; border-top: 1px solid #8883; }}
  .when {{ color: #6b7280; font-variant-numeric: tabular-nums; margin-right: .5rem; }}
  .dur {{ color: #6b7280; margin-left: .5rem; }}
  .title {{ font-weight: 600; }}
  audio {{ display: block; width: 100%; margin-top: .5rem; }}
</style>
</head>
<body>
<h1>{esc(spec.get('title', 'Podcast'))}</h1>
<p class="sub">{esc(spec.get('description', ''))}</p>
<p>Subscribe in any podcast app: <code>{esc(base)}/feed.xml</code></p>
<ul>
{chr(10).join(rows)}
</ul>
<footer><p class="sub">{len(episodes)} episode(s) · latest {latest} · generated by digest-engine</p></footer>
</body>
</html>
"""


def _with_hosted_cover(spec: dict, site: Path, base: str) -> dict:
    """A cover given as a local path is copied into the site and re-pointed at it."""
    cover = spec.get("cover_image", "")
    if not cover or cover.startswith(("http://", "https://")):
        return spec
    src = resolve(spec, cover)
    if not src.exists():
        print(f"  ! cover_image not found: {src}")
        return spec
    dst = site / f"cover{src.suffix or '.png'}"
    shutil.copy2(src, dst)
    return {**spec, "cover_image": f"{base}/{dst.name}"}


def _readme(spec: dict, base: str, count: int) -> str:
    return f"""# {spec.get('title', 'Podcast')}

{spec.get('description', '')}

**Feed:** `{base}/feed.xml` — paste that into any podcast app.
**Web player:** {base}/

Generated by [digest-engine](https://github.com/Temp-Security-Startup/digest-engine).
This branch is rebuilt and force-pushed on every publish, so it always holds
exactly the {count} most recent episode(s) and no history.

Episodes contain narrated articles or original audio imported from linked videos.
Every episode links to its source. Not affiliated with the source publishers.
"""


def build(spec: dict, store: Store) -> Path:
    """Assemble the publishable site directory and return it."""
    site = resolve(spec, spec["paths"].get("site_dir", "output/site"))
    audio_dir = site / "audio"
    audio_dir.mkdir(parents=True, exist_ok=True)

    episodes = _kept(spec, store)
    wanted: set[str] = set()
    for ep in episodes:
        src = Path(ep.audio_path)
        dst = audio_dir / src.name
        wanted.add(src.name)
        if not dst.exists() or dst.stat().st_size != src.stat().st_size:
            shutil.copy2(src, dst)

    pruned = 0
    for stale in audio_dir.glob("*.mp3"):
        if stale.name not in wanted:
            stale.unlink()
            pruned += 1

    base = base_url(spec)
    spec = _with_hosted_cover(spec, site, base)
    publish_mod.podcast_feed(episodes, spec, base, site / "feed.xml")
    (site / "index.html").write_text(_index_html(spec, episodes, base), encoding="utf-8")
    (site / ".nojekyll").write_text("", encoding="utf-8")
    (site / "README.md").write_text(_readme(spec, base, len(episodes)), encoding="utf-8")

    cname = _publish_cfg(spec).get("cname", "")
    if cname:
        (site / "CNAME").write_text(f"{cname}\n", encoding="utf-8")

    print(f"  site: {len(episodes)} episode(s), {pruned} pruned -> {site}")
    return site


def push(spec: dict, site: Path) -> None:
    """Force-push the site as a single orphan commit."""
    cfg = _publish_cfg(spec)
    repo = cfg.get("repo", "")
    if not repo:
        print("  ! publish.repo not set — built the site but did not push")
        return
    branch = cfg.get("branch", "main")
    url = repo if repo.startswith(("http", "git@")) else f"https://github.com/{repo}.git"

    if not (site / ".git").exists():
        _git(site, "init", "-q", "-b", branch)
        _git(site, "remote", "add", "origin", url)
    else:
        _git(site, "remote", "set-url", "origin", url, check=False)

    if not _git(site, "config", "user.email", check=False).stdout.strip():
        _git(site, "config", "user.email", "digest-engine@localhost")
        _git(site, "config", "user.name", "digest-engine")
    if shutil.which("gh"):
        # Local-scope only: authenticate the push through the gh CLI instead of
        # whatever global credential helper happens to be configured.
        _git(site, "config", "credential.https://github.com.helper", "", check=False)
        _git(site, "config", "--add", "credential.https://github.com.helper",
             "!gh auth git-credential", check=False)

    # Every publish is a fresh orphan commit, so "nothing to commit" never fires.
    # Compare the staged tree against the branch's tree instead.
    _git(site, "add", "-A")
    tree = _git(site, "write-tree").stdout.strip()
    head_tree = _git(site, "rev-parse", "-q", "--verify", f"{branch}^{{tree}}",
                     check=False).stdout.strip()
    if tree and tree == head_tree:
        print("  site unchanged; nothing to push")
        return

    now = datetime.now(timezone.utc)
    tmp = f"_publish_{now:%Y%m%d%H%M%S}"   # unique: a crashed publish can't wedge the next
    _git(site, "checkout", "-q", "--orphan", tmp)
    _git(site, "add", "-A")
    commit = _git(site, "commit", "-q", "-m", f"publish {now:%Y-%m-%d %H:%M UTC}", check=False)
    if commit.returncode != 0:
        raise RuntimeError(f"git commit failed: {commit.stdout}{commit.stderr}")

    _git(site, "branch", "-q", "-M", branch)
    pushed = _git(site, "push", "--force", "-q", "origin", branch, check=False)
    if pushed.returncode != 0:
        raise RuntimeError(f"git push failed: {pushed.stdout}{pushed.stderr}")
    print(f"  pushed to {repo} ({branch}) — {base_url(spec)}/feed.xml")


def publish(spec_path: str, *, push_site: bool = True) -> Path:
    load_dotenv()
    spec = load_spec(spec_path)
    store = Store(resolve(spec, spec["paths"]["db_file"]))
    site = build(spec, store)
    if push_site:
        push(spec, site)
    return site
